-- Requirement 4: the student record stored in PostgreSQL.
-- One MongoDB document maps to 10 normalized tables (the same tables and columns as in lab 1,
-- without the audit / soft delete columns that the document does not contain).

DROP SCHEMA IF EXISTS public CASCADE;
CREATE SCHEMA public;

CREATE TYPE degree_level      AS ENUM ('bachelor', 'master', 'phd');
CREATE TYPE teacher_position  AS ENUM ('assistant', 'senior_lecturer', 'associate_professor', 'professor');
CREATE TYPE student_status    AS ENUM ('active', 'academic_leave', 'expelled', 'graduated');
CREATE TYPE funding_type      AS ENUM ('budget', 'contract');
CREATE TYPE control_form      AS ENUM ('exam', 'credit', 'diff_credit');
CREATE TYPE enrollment_status AS ENUM ('enrolled', 'completed', 'failed', 'dropped');
CREATE TYPE assessment_type   AS ENUM ('lab', 'practice', 'test', 'module', 'coursework', 'exam', 'bonus');

CREATE TABLE faculties (
    id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code  varchar(10)  NOT NULL,
    name  varchar(200) NOT NULL
);

CREATE TABLE departments (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    faculty_id  bigint       NOT NULL,
    code        varchar(10)  NOT NULL,
    name        varchar(200) NOT NULL
);

CREATE TABLE specialties (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id  bigint       NOT NULL,
    code           varchar(10)  NOT NULL,
    name           varchar(200) NOT NULL,
    degree_level   degree_level NOT NULL DEFAULT 'bachelor'
);

CREATE TABLE teachers (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id    bigint           NOT NULL,
    last_name        varchar(100)     NOT NULL,
    first_name       varchar(100)     NOT NULL,
    middle_name      varchar(100),
    position         teacher_position NOT NULL,
    academic_degree  varchar(50)
);

CREATE TABLE student_groups (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    specialty_id        bigint      NOT NULL,
    code                varchar(20) NOT NULL,
    admission_year      smallint    NOT NULL,
    curator_teacher_id  bigint
);

CREATE TABLE students (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id         bigint         NOT NULL,
    record_book_no   varchar(20)    NOT NULL,
    last_name        varchar(100)   NOT NULL,
    first_name       varchar(100)   NOT NULL,
    middle_name      varchar(100),
    birth_date       date           NOT NULL,
    email            varchar(255),
    phone            varchar(20),
    enrollment_date  date           NOT NULL,
    status           student_status NOT NULL,
    funding          funding_type   NOT NULL
);

CREATE TABLE semesters (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    academic_year  varchar(9) NOT NULL,
    term           smallint   NOT NULL,
    start_date     date       NOT NULL,
    end_date       date       NOT NULL
);

CREATE TABLE courses (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id  bigint       NOT NULL,
    code           varchar(20)  NOT NULL,
    name           varchar(200) NOT NULL,
    credits        numeric(4,1) NOT NULL,
    control        control_form NOT NULL
);

CREATE TABLE enrollments (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id      bigint            NOT NULL,
    course_id       bigint            NOT NULL,
    semester_id     bigint            NOT NULL,
    status          enrollment_status NOT NULL,
    total_score     numeric(5,2),
    ects_grade      varchar(2),
    national_grade  varchar(20)
);

CREATE TABLE grades (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enrollment_id    bigint          NOT NULL,
    assessment_type  assessment_type NOT NULL,
    title            varchar(100)    NOT NULL,
    score            numeric(5,2)    NOT NULL,
    max_score        numeric(5,2)    NOT NULL,
    graded_on        date            NOT NULL,
    teacher_id       bigint
);

-- Requirement 5: the same document as in MongoDB stored in PostgreSQL jsonb (extra variant for the benchmark)
CREATE TABLE student_records (
    id   bigint PRIMARY KEY,
    doc  jsonb NOT NULL
);
